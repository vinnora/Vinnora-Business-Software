import { NextRequest, NextResponse } from 'next/server';
import { getServerSession } from 'next-auth/next';
import { authOptions } from '@/lib/auth';
import dbConnect from '@/lib/mongodb';
import ReorderRule from '@/models/ReorderRule';
import Item from '@/models/Item';
import PurchaseOrder from '@/models/PurchaseOrder';

function genPONumber() {
  const year = new Date().getFullYear();
  const random = Math.floor(Math.random() * 100000).toString().padStart(5, '0');
  return `PO-${year}-${random}`;
}

export async function GET(_req: NextRequest) {
  try {
    await dbConnect();
    const session = await getServerSession(authOptions);
    const userId = session?.user?.email || 'dev-user-id';
    const items = await ReorderRule.find({ userId }).sort({ createdAt: -1 });
    return NextResponse.json(items);
  } catch {
    return NextResponse.json([], { status: 200 });
  }
}

export async function POST(req: NextRequest) {
  try {
    await dbConnect();
    const session = await getServerSession(authOptions);
    const userId = session?.user?.email || 'dev-user-id';
    const body = await req.json();

    if (body.action === 'run' && body.ruleId) {
      const rule = await ReorderRule.findById(body.ruleId);
      if (!rule) return NextResponse.json({ error: 'Rule not found' }, { status: 404 });

      // Find items needing reorder
      const filter: any = { userId };
      if (rule.appliesTo === 'category' && rule.categoryFilter) {
        filter.category = rule.categoryFilter;
      } else if (rule.appliesTo === 'item' && rule.itemIds.length > 0) {
        filter._id = { $in: rule.itemIds };
      }
      filter.$expr = { $lte: ['$totalStock', rule.reorderPoint] };

      const lowItems = await Item.find(filter);
      const created = [];

      for (const item of lowItems) {
        const supplier =
          item.suppliers?.find((s: any) => s.isPreferred) || item.suppliers?.[0];
        if (!supplier) continue;
        const quantity = rule.reorderQuantity;
        const unitCost = supplier.costPrice || item.costPrice || 0;
        const lineSub = quantity * unitCost;
        const taxAmount = (lineSub * (item.taxRate || 0)) / 100;
        const po = await PurchaseOrder.create({
          userId,
          poNumber: genPONumber(),
          supplierId: supplier.supplierId,
          supplierName: supplier.supplierName,
          warehouseId: rule.warehouseId,
          orderDate: new Date(),
          expectedDate: new Date(
            Date.now() + (supplier.leadTimeDays || 7) * 24 * 60 * 60 * 1000
          ),
          lines: [
            {
              itemId: String(item._id),
              itemCode: item.itemCode,
              itemName: item.name,
              quantity,
              receivedQuantity: 0,
              unitCost,
              taxRate: item.taxRate || 0,
              discount: 0,
              total: lineSub + taxAmount,
            },
          ],
          subtotal: lineSub,
          taxTotal: taxAmount,
          total: lineSub + taxAmount,
          status: rule.requireApproval ? 'draft' : 'sent',
          isAutoGenerated: true,
          generatedFromRule: String(rule._id),
        });
        created.push(po);
      }

      rule.lastTriggeredAt = new Date();
      rule.triggerCount = (rule.triggerCount || 0) + 1;
      await rule.save();
      return NextResponse.json({ rule, ordersCreated: created.length, orders: created });
    }

    if (!body.name) return NextResponse.json({ error: 'name required' }, { status: 400 });
    const r = await ReorderRule.create({ ...body, userId });
    return NextResponse.json(r, { status: 201 });
  } catch (error: any) {
    return NextResponse.json({ error: error.message || 'Failed' }, { status: 500 });
  }
}

export async function PATCH(req: NextRequest) {
  try {
    await dbConnect();
    const body = await req.json();
    const { _id, ...updates } = body;
    if (!_id) return NextResponse.json({ error: '_id required' }, { status: 400 });
    const r = await ReorderRule.findByIdAndUpdate(_id, updates, { new: true });
    return NextResponse.json(r);
  } catch {
    return NextResponse.json({ error: 'Failed' }, { status: 500 });
  }
}

export async function DELETE(req: NextRequest) {
  try {
    await dbConnect();
    const { searchParams } = new URL(req.url);
    const id = searchParams.get('id');
    if (!id) return NextResponse.json({ error: 'id required' }, { status: 400 });
    await ReorderRule.findByIdAndDelete(id);
    return NextResponse.json({ success: true });
  } catch {
    return NextResponse.json({ error: 'Failed' }, { status: 500 });
  }
}
