import InventoryWorkflowRule, {
  IInventoryWorkflowCondition,
  IInventoryWorkflowAction,
  InventoryWorkflowObject,
  InventoryWorkflowEvent,
} from '@/models/InventoryWorkflowRule';
import PurchaseOrder from '@/models/PurchaseOrder';
import StockTransfer from '@/models/StockTransfer';
import StockAudit from '@/models/StockAudit';

/** Fields a workflow rule may never set. */
const PROTECTED_FIELDS = new Set(['_id', 'orgId', 'userId', 'createdAt', 'updatedAt', '__v']);

/**
 * Inventory rule engine. Mirrors the sales-service workflow engine.
 * Best-effort: failures never block the user request.
 */

function getField(obj: any, path: string): any {
  return path.split('.').reduce((acc, k) => (acc == null ? acc : acc[k]), obj);
}

function evalCondition(record: any, c: IInventoryWorkflowCondition): boolean {
  const v = getField(record, c.field);
  switch (c.operator) {
    case 'equals':
      return String(v) === String(c.value);
    case 'notEquals':
      return String(v) !== String(c.value);
    case 'contains':
      return String(v ?? '').toLowerCase().includes(String(c.value ?? '').toLowerCase());
    case 'greaterThan':
      return Number(v) > Number(c.value);
    case 'lessThan':
      return Number(v) < Number(c.value);
    case 'isEmpty':
      return v == null || v === '' || (Array.isArray(v) && v.length === 0);
    case 'isNotEmpty':
      return !(v == null || v === '' || (Array.isArray(v) && v.length === 0));
    default:
      return false;
  }
}

function evalConditions(
  record: any,
  conditions: IInventoryWorkflowCondition[],
  logic: 'AND' | 'OR'
): boolean {
  if (!conditions || conditions.length === 0) return true;
  if (logic === 'OR') return conditions.some((c) => evalCondition(record, c));
  return conditions.every((c) => evalCondition(record, c));
}

function interpolate(template: string, record: any): string {
  return String(template ?? '').replace(/\{\{\s*([\w.]+)\s*\}\}/g, (_m, key) => {
    const v = getField(record, key);
    return v == null ? '' : String(v);
  });
}

function genPONumber() {
  const year = new Date().getFullYear();
  const random = Math.floor(Math.random() * 100000).toString().padStart(5, '0');
  return `PO-${year}-${random}`;
}

function genTransferNumber() {
  const year = new Date().getFullYear();
  const random = Math.floor(Math.random() * 100000).toString().padStart(5, '0');
  return `TRF-${year}-${random}`;
}

function genAuditNumber() {
  const year = new Date().getFullYear();
  const random = Math.floor(Math.random() * 100000).toString().padStart(5, '0');
  return `AUDIT-${year}-${random}`;
}

async function executeAction(
  action: IInventoryWorkflowAction,
  record: any,
  objectType: InventoryWorkflowObject,
  userId: string,
  orgId?: string
) {
  const params = action.params || {};
  // Stamp the workspace on anything created when the caller knows it.
  const owner = orgId ? { userId, orgId } : { userId };
  switch (action.type) {
    case 'createPurchaseOrder': {
      if (objectType !== 'Item') break;
      const supplier =
        record.suppliers?.find((s: any) => s.isPreferred) || record.suppliers?.[0];
      if (!supplier) break;
      const quantity = params.quantity || record.reorderQuantity || 50;
      const unitCost = supplier.costPrice || record.costPrice || 0;
      const lineTotal = quantity * unitCost;
      await PurchaseOrder.create({
        ...owner,
        poNumber: genPONumber(),
        supplierId: supplier.supplierId,
        supplierName: supplier.supplierName,
        warehouseId: params.warehouseId,
        warehouseName: params.warehouseName,
        orderDate: new Date(),
        expectedDate: new Date(Date.now() + (supplier.leadTimeDays || 7) * 24 * 60 * 60 * 1000),
        lines: [
          {
            itemId: String(record._id),
            itemCode: record.itemCode,
            itemName: record.name,
            quantity,
            receivedQuantity: 0,
            unitCost,
            taxRate: record.taxRate || 0,
            discount: 0,
            total: lineTotal,
          },
        ],
        subtotal: lineTotal,
        total: lineTotal + lineTotal * ((record.taxRate || 0) / 100),
        taxTotal: lineTotal * ((record.taxRate || 0) / 100),
        status: params.autoSend ? 'sent' : 'draft',
        isAutoGenerated: true,
      });
      break;
    }
    case 'createStockTransfer': {
      if (objectType !== 'Item') break;
      if (!params.fromWarehouseId || !params.toWarehouseId) break;
      await StockTransfer.create({
        ...owner,
        transferNumber: genTransferNumber(),
        fromWarehouseId: params.fromWarehouseId,
        fromWarehouseName: params.fromWarehouseName || '',
        toWarehouseId: params.toWarehouseId,
        toWarehouseName: params.toWarehouseName || '',
        initiatedDate: new Date(),
        status: 'draft',
        lines: [
          {
            itemId: String(record._id),
            itemCode: record.itemCode,
            itemName: record.name,
            requestedQuantity: params.quantity || 10,
            shippedQuantity: 0,
            receivedQuantity: 0,
          },
        ],
        totalQuantity: params.quantity || 10,
        reason: 'Auto-generated by workflow',
      });
      break;
    }
    case 'createStockAudit': {
      if (!params.warehouseId) break;
      await StockAudit.create({
        ...owner,
        auditNumber: genAuditNumber(),
        warehouseId: params.warehouseId,
        warehouseName: params.warehouseName || '',
        type: params.type || 'partial',
        scheduledDate: new Date(),
        status: 'draft',
      });
      break;
    }
    case 'updateField': {
      // Ownership/system fields are never changed by a rule.
      if (!params.field || PROTECTED_FIELDS.has(String(params.field).split('.')[0])) break;
      record[params.field] = interpolate(String(params.value ?? ''), record) || params.value;
      await record.save();
      break;
    }
    case 'sendAlert': {
      // Records to console; real impl would push to a notification system.
      console.info('[InventoryAlert]', interpolate(params.message || 'Alert', record));
      break;
    }
    case 'sendEmail': {
      console.info(
        '[InventoryEmail]',
        params.to,
        interpolate(params.subject || '', record),
        interpolate(params.body || '', record)
      );
      break;
    }
    case 'webhook': {
      if (!params.url) break;
      try {
        await fetch(params.url, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ objectType, record }),
        });
      } catch {
        // swallow
      }
      break;
    }
    case 'logEvent': {
      console.info('[InventoryEvent]', objectType, interpolate(params.message || '', record));
      break;
    }
  }
}

export async function runInventoryWorkflows(opts: {
  objectType: InventoryWorkflowObject;
  event: InventoryWorkflowEvent;
  record: any;
  userId: string;
  /** Workspace key stamped on records created by actions. */
  orgId?: string;
  /** Workspace filter from getTenant().where(); when given, the workspace's rules run instead of only this user's. */
  scope?: Record<string, unknown>;
  changedFields?: string[];
}) {
  try {
    const { objectType, event, record, userId, orgId, scope, changedFields } = opts;
    const filter: any = scope ? { objectType, active: true } : { userId, objectType, active: true };
    if (event === 'fieldChanged') {
      filter.triggerEvent = { $in: ['fieldChanged', 'updated'] };
    } else {
      filter.triggerEvent = event;
    }

    const rules = await InventoryWorkflowRule.find(scope ? { $and: [scope, filter] } : filter);
    for (const rule of rules) {
      if (rule.triggerEvent === 'fieldChanged') {
        if (!rule.watchFields || rule.watchFields.length === 0) continue;
        if (!changedFields || !changedFields.some((f) => rule.watchFields!.includes(f))) continue;
      }
      if (!evalConditions(record, rule.conditions, rule.conditionLogic)) continue;

      for (const action of rule.actions) {
        await executeAction(action, record, objectType, userId, orgId);
      }
      rule.runCount = (rule.runCount || 0) + 1;
      rule.lastRunAt = new Date();
      await rule.save();
    }
  } catch (err) {
    console.error('Inventory workflow engine error:', err);
  }
}

/**
 * Helper for the items API to detect low stock and trigger reorder workflows.
 */
export async function checkAndTriggerReorder(
  item: any,
  userId: string,
  tenant?: { orgId: string; scope: Record<string, unknown> }
) {
  const ws = tenant ? { orgId: tenant.orgId, scope: tenant.scope } : {};
  if (item.totalStock <= 0) {
    await runInventoryWorkflows({
      objectType: 'Item',
      event: 'outOfStock',
      record: item,
      userId,
      ...ws,
    });
  } else if (item.reorderPoint > 0 && item.totalStock <= item.reorderPoint) {
    await runInventoryWorkflows({
      objectType: 'Item',
      event: 'lowStock',
      record: item,
      userId,
      ...ws,
    });
  }

  if (item.expiryDate) {
    const daysUntilExpiry = Math.floor(
      (new Date(item.expiryDate).getTime() - Date.now()) / (1000 * 60 * 60 * 24)
    );
    if (daysUntilExpiry > 0 && daysUntilExpiry <= 30) {
      await runInventoryWorkflows({
        objectType: 'Item',
        event: 'expiringSoon',
        record: item,
        userId,
        ...ws,
      });
    }
  }
}
