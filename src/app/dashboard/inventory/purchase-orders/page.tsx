'use client';

import { useEffect, useState } from 'react';
import {
  PageHeader,
  Modal,
  Field,
  TextInput,
  TextArea,
  SelectInput,
  PrimaryButton,
  SecondaryButton,
  Badge,
  Tile,
  fmtINR,
} from '../_components/ui';

type Line = {
  itemId: string;
  itemCode: string;
  itemName: string;
  quantity: number;
  receivedQuantity: number;
  unitCost: number;
  taxRate: number;
  discount: number;
  total: number;
};

type PO = {
  _id: string;
  poNumber: string;
  supplierId: string;
  supplierName: string;
  warehouseName?: string;
  orderDate: string;
  expectedDate: string;
  receivedDate?: string;
  status: string;
  lines: Line[];
  subtotal: number;
  taxTotal: number;
  shippingCost: number;
  total: number;
  paymentStatus: string;
  isAutoGenerated: boolean;
};

const STATUSES = ['draft', 'sent', 'acknowledged', 'partial-received', 'received', 'cancelled'];
const STATUS_TONE: Record<string, any> = {
  draft: 'gray',
  sent: 'blue',
  acknowledged: 'purple',
  'partial-received': 'amber',
  received: 'green',
  cancelled: 'red',
};

export default function PurchaseOrdersPage() {
  const [items, setItems] = useState<PO[]>([]);
  const [suppliers, setSuppliers] = useState<any[]>([]);
  const [warehouses, setWarehouses] = useState<any[]>([]);
  const [products, setProducts] = useState<any[]>([]);
  const [loading, setLoading] = useState(true);
  const [statusFilter, setStatusFilter] = useState('');
  const [open, setOpen] = useState(false);
  const [form, setForm] = useState<any>(empty());

  function empty() {
    return {
      orderDate: new Date().toISOString().slice(0, 10),
      expectedDate: new Date(Date.now() + 7 * 86400000).toISOString().slice(0, 10),
      lines: [{ itemId: '', itemCode: '', itemName: '', quantity: 1, unitCost: 0, taxRate: 18, discount: 0 }],
      shippingCost: 0,
      paymentTerms: 'Net 30',
    };
  }

  const load = async () => {
    setLoading(true);
    const params = new URLSearchParams();
    if (statusFilter) params.set('status', statusFilter);
    const data = await fetch(`/api/inventory/purchase-orders?${params}`).then((r) => r.json());
    setItems(Array.isArray(data) ? data : []);
    setLoading(false);
  };

  const loadRefs = async () => {
    const [s, w, p] = await Promise.all([
      fetch('/api/inventory/suppliers').then((r) => r.json()),
      fetch('/api/inventory/warehouses').then((r) => r.json()),
      fetch('/api/inventory/items').then((r) => r.json()),
    ]);
    setSuppliers(Array.isArray(s) ? s : []);
    setWarehouses(Array.isArray(w) ? w : []);
    setProducts(Array.isArray(p) ? p : []);
  };

  useEffect(() => {
    load();
  }, [statusFilter]);

  useEffect(() => {
    loadRefs();
  }, []);

  const addLine = () =>
    setForm({
      ...form,
      lines: [
        ...form.lines,
        { itemId: '', itemCode: '', itemName: '', quantity: 1, unitCost: 0, taxRate: 18, discount: 0 },
      ],
    });

  const updateLine = (i: number, patch: any) => {
    setForm({
      ...form,
      lines: form.lines.map((l: any, idx: number) => (idx === i ? { ...l, ...patch } : l)),
    });
  };

  const removeLine = (i: number) =>
    setForm({ ...form, lines: form.lines.filter((_: any, idx: number) => idx !== i) });

  const selectItemForLine = (i: number, itemId: string) => {
    const product = products.find((p) => p._id === itemId);
    if (!product) return;
    updateLine(i, {
      itemId: product._id,
      itemCode: product.itemCode,
      itemName: product.name,
      unitCost: product.costPrice,
      taxRate: product.taxRate,
    });
  };

  const computedTotal = form.lines.reduce(
    (s: number, l: any) =>
      s +
      ((l.quantity || 0) * (l.unitCost || 0) - (l.discount || 0)) *
        (1 + (l.taxRate || 0) / 100),
    0
  ) + (Number(form.shippingCost) || 0);

  const save = async () => {
    if (!form.supplierId || form.lines.length === 0) return;
    const supplier = suppliers.find((s) => s._id === form.supplierId);
    const warehouse = warehouses.find((w) => w._id === form.warehouseId);
    await fetch('/api/inventory/purchase-orders', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        ...form,
        supplierName: supplier?.name,
        warehouseName: warehouse?.name,
      }),
    });
    setOpen(false);
    setForm(empty());
    load();
  };

  const updateStatus = async (id: string, status: string) => {
    await fetch('/api/inventory/purchase-orders', {
      method: 'PATCH',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ _id: id, status }),
    });
    load();
  };

  const receiveAll = async (id: string) => {
    if (!confirm('Mark as fully received and increment warehouse stock?')) return;
    await fetch('/api/inventory/purchase-orders', {
      method: 'PATCH',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ _id: id, receiveAll: true }),
    });
    load();
  };

  const remove = async (id: string) => {
    if (!confirm('Delete this PO?')) return;
    await fetch(`/api/inventory/purchase-orders?id=${id}`, { method: 'DELETE' });
    load();
  };

  return (
    <>
      <PageHeader
        title="Purchase Orders"
        subtitle="Procurement"
        count={items.length}
        actions={
          <>
            <SelectInput value={statusFilter} onChange={(e) => setStatusFilter(e.target.value)}>
              <option value="">All statuses</option>
              {STATUSES.map((s) => <option key={s}>{s}</option>)}
            </SelectInput>
            <PrimaryButton onClick={() => setOpen(true)}>+ New PO</PrimaryButton>
          </>
        }
      />

      <div className="p-6">
        <div className="grid grid-cols-4 gap-3 mb-4">
          <Tile label="Total POs" value={items.length} tone="fire" />
          <Tile
            label="Open Value"
            value={fmtINR(
              items
                .filter((i) => !['received', 'cancelled'].includes(i.status))
                .reduce((s, i) => s + i.total, 0)
            )}
            tone="amber"
          />
          <Tile
            label="Auto-generated"
            value={items.filter((i) => i.isAutoGenerated).length}
            tone="glow"
            hint="By reorder rules"
          />
          <Tile
            label="Received"
            value={items.filter((i) => i.status === 'received').length}
            tone="fire"
          />
        </div>

        <div className="bg-white border border-[#FFE5C4] rounded-lg overflow-hidden">
          <table className="w-full text-sm">
            <thead className="bg-[#FFF6E5] text-xs uppercase text-[#6B2410]">
              <tr>
                <th className="text-left px-4 py-2.5">PO #</th>
                <th className="text-left px-4 py-2.5">Supplier</th>
                <th className="text-left px-4 py-2.5">Warehouse</th>
                <th className="text-left px-4 py-2.5">Order Date</th>
                <th className="text-left px-4 py-2.5">Expected</th>
                <th className="text-right px-4 py-2.5">Total</th>
                <th className="text-left px-4 py-2.5">Status</th>
                <th></th>
              </tr>
            </thead>
            <tbody>
              {loading ? (
                <tr><td colSpan={8} className="px-4 py-8 text-center text-[#A0522D]">Loading…</td></tr>
              ) : items.length === 0 ? (
                <tr><td colSpan={8} className="px-4 py-8 text-center text-[#A0522D]">No purchase orders yet.</td></tr>
              ) : items.map((po) => (
                <tr key={po._id} className="border-t border-[#FFF1D6] hover:bg-[#FFF6E5]">
                  <td className="px-4 py-2 font-mono text-xs text-[#4A1D0F]">
                    {po.poNumber}
                    {po.isAutoGenerated && (
                      <div className="text-[9px] text-[#E2671A]">⚡ auto</div>
                    )}
                  </td>
                  <td className="px-4 py-2 font-medium text-[#4A1D0F]">{po.supplierName}</td>
                  <td className="px-4 py-2 text-[#6B2410]">{po.warehouseName || '—'}</td>
                  <td className="px-4 py-2 text-[#6B2410]">{new Date(po.orderDate).toLocaleDateString()}</td>
                  <td className="px-4 py-2 text-[#6B2410]">{new Date(po.expectedDate).toLocaleDateString()}</td>
                  <td className="px-4 py-2 text-right font-semibold">{fmtINR(po.total)}</td>
                  <td className="px-4 py-2">
                    <select
                      value={po.status}
                      onChange={(e) => updateStatus(po._id, e.target.value)}
                      className="text-xs border-0 rounded px-1 py-0.5 bg-white"
                    >
                      {STATUSES.map((s) => <option key={s}>{s}</option>)}
                    </select>
                  </td>
                  <td className="px-4 py-2 text-right whitespace-nowrap">
                    {po.status !== 'received' && po.status !== 'cancelled' && (
                      <button onClick={() => receiveAll(po._id)} className="text-xs text-green-700 hover:underline mr-2">
                        Receive
                      </button>
                    )}
                    <button onClick={() => remove(po._id)} className="text-xs text-red-600 hover:underline">
                      Delete
                    </button>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </div>

      <Modal
        open={open}
        onClose={() => setOpen(false)}
        title="New Purchase Order"
        width="max-w-4xl"
        footer={
          <>
            <SecondaryButton onClick={() => setOpen(false)}>Cancel</SecondaryButton>
            <PrimaryButton onClick={save}>Save</PrimaryButton>
          </>
        }
      >
        <div className="grid grid-cols-3 gap-3">
          <Field label="Supplier" required>
            <SelectInput value={form.supplierId || ''} onChange={(e) => setForm({ ...form, supplierId: e.target.value })}>
              <option value="">— Select supplier —</option>
              {suppliers.map((s) => <option key={s._id} value={s._id}>{s.name}</option>)}
            </SelectInput>
          </Field>
          <Field label="Warehouse">
            <SelectInput value={form.warehouseId || ''} onChange={(e) => setForm({ ...form, warehouseId: e.target.value })}>
              <option value="">—</option>
              {warehouses.map((w) => <option key={w._id} value={w._id}>{w.name}</option>)}
            </SelectInput>
          </Field>
          <Field label="Order Date">
            <TextInput type="date" value={form.orderDate} onChange={(e) => setForm({ ...form, orderDate: e.target.value })} />
          </Field>
          <Field label="Expected Date">
            <TextInput type="date" value={form.expectedDate} onChange={(e) => setForm({ ...form, expectedDate: e.target.value })} />
          </Field>
          <Field label="Payment Terms">
            <TextInput value={form.paymentTerms || ''} onChange={(e) => setForm({ ...form, paymentTerms: e.target.value })} />
          </Field>
          <Field label="Shipping Cost (₹)">
            <TextInput type="number" value={form.shippingCost} onChange={(e) => setForm({ ...form, shippingCost: e.target.value })} />
          </Field>
        </div>

        <div className="mt-3 mb-2 flex items-center justify-between">
          <h3 className="text-sm font-semibold text-[#4A1D0F]">Line Items</h3>
          <button onClick={addLine} className="text-xs text-[#E2671A]">+ Add line</button>
        </div>
        {form.lines.map((l: any, i: number) => (
          <div key={i} className="grid grid-cols-12 gap-2 mb-2">
            <select
              value={l.itemId}
              onChange={(e) => selectItemForLine(i, e.target.value)}
              className="col-span-4 px-2 py-1 text-sm border border-[#FFE5C4] rounded bg-white"
            >
              <option value="">— Item —</option>
              {products.map((p) => <option key={p._id} value={p._id}>{p.itemCode} — {p.name}</option>)}
            </select>
            <input
              type="number"
              placeholder="Qty"
              value={l.quantity}
              onChange={(e) => updateLine(i, { quantity: Number(e.target.value) })}
              className="col-span-2 px-2 py-1 text-sm border border-[#FFE5C4] rounded"
            />
            <input
              type="number"
              placeholder="Cost"
              value={l.unitCost}
              onChange={(e) => updateLine(i, { unitCost: Number(e.target.value) })}
              className="col-span-2 px-2 py-1 text-sm border border-[#FFE5C4] rounded"
            />
            <input
              type="number"
              placeholder="Tax%"
              value={l.taxRate}
              onChange={(e) => updateLine(i, { taxRate: Number(e.target.value) })}
              className="col-span-1 px-2 py-1 text-sm border border-[#FFE5C4] rounded"
            />
            <input
              type="number"
              placeholder="Disc"
              value={l.discount}
              onChange={(e) => updateLine(i, { discount: Number(e.target.value) })}
              className="col-span-2 px-2 py-1 text-sm border border-[#FFE5C4] rounded"
            />
            <button onClick={() => removeLine(i)} className="col-span-1 text-red-600 text-xs">×</button>
          </div>
        ))}
        <div className="text-right pt-3 border-t border-[#FFE5C4] mt-3">
          <div className="text-lg font-semibold text-[#4A1D0F]">Total: {fmtINR(computedTotal)}</div>
        </div>
      </Modal>
    </>
  );
}
